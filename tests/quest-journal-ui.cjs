const { run, debug } = require('./lib/touch.cjs');
const suite = {
  name: 'quest-journal',
  async test({ player, check: assertCheck, sleep, width, height, out }) {
    const check = (v, label) => { assertCheck(v, label); console.log(label); };
    const page = await player('JournalTester');
    const ledger = id => page.evaluate(id => Field.hero.quests.find(q => q.id === id), id);
    async function visit(zone, id) {
      await page.evaluate(() => { City.close(); Quests.close(); });
      const n = await page.evaluate(({zone,id}) => [WORLD_MAP,...WORLD_MAP.zones][zone].npcs.find(n => n.id===id), {zone,id});
      await debug(page,{op:'teleport',zone,x:n.x+1,y:n.y});
      await page.waitForFunction(({zone,n})=>Field.zone===zone&&Math.hypot(Field.hero.nx-n.x-1,Field.hero.ny-n.y)<.3,{zone,n});
      await sleep(550); await page.evaluate(npc=>Online.send({type:'interact',npc}),id);
      await page.locator('#npc-dialogue').waitFor({state:'visible'});
      if (await page.locator('#npc-back').isVisible()) await page.locator('#npc-back').tap();
    }
    await visit(0,'gatekeeper');
    check(await page.locator('#npc-close').count()===0 && !await page.getByRole('button',{name:'Goodbye',exact:true}).count(),'conversation has no Goodbye button');
    await page.locator('#npc-x').tap(); check(!await page.locator('#npc-dialogue').isVisible(),'X closes conversation');
    await visit(0,'gatekeeper');
    await page.touchscreen.tap(2,2);
    check(!await page.locator('#npc-dialogue').isVisible(),'outside press still closes conversation');
    await visit(0,'gatekeeper'); await page.locator('#npc-quests [data-quest="slime_patrol"]').tap();
    await page.locator('#npc-quests [data-action="accept"]').tap();
    await page.locator('#npc-dialogue').waitFor({state:'hidden'});
    await page.evaluate(()=>Quests.show());
    const entry=page.locator('#quest-list .quest-entry[data-quest="slime_patrol"]');
    check(await entry.count()===1 && !await entry.evaluate(n=>n.open),'accepted quest starts collapsed');
    check((await entry.locator(':scope > summary').textContent())==='! Trouble at the Gate','collapsed row contains only ! and quest title');
    check(!await entry.locator('.quest-objectives').isVisible(),'collapsed objectives are hidden');
    await entry.locator(':scope > summary').focus(); await page.keyboard.press('Enter');
    check(await entry.locator('.quest-objectives').isVisible(),'keyboard activation expands details');
    await debug(page,{op:'quest',id:'slime_patrol',action:'complete'});
    await page.waitForFunction(()=>Field.hero.quests.find(q=>q.id==='slime_patrol').counts[0]>=6);
    check(await entry.evaluate(n=>n.open),'live progress keeps the selected quest expanded');
    await entry.getByRole('button',{name:'Track quest',exact:true}).tap();
    await entry.getByRole('button',{name:'Abandon quest',exact:true}).tap();
    await entry.getByRole('button',{name:'Cancel',exact:true}).tap();
    check(!!await ledger('slime_patrol'),'cancel preserves quest');
    await entry.getByRole('button',{name:'Abandon quest',exact:true}).tap();
    const before=await page.evaluate(()=>({xp:Field.hero.xp,gold:Field.hero.gold}));
    await entry.getByRole('button',{name:'Confirm abandon',exact:true}).tap();
    await page.waitForFunction(()=>!Field.hero.quests.some(q=>q.id==='slime_patrol'));
    check(await entry.count()===0,'confirm abandons ready quest through server');
    check(await page.evaluate(b=>Field.hero.xp===b.xp&&Field.hero.gold===b.gold,before),'abandon pays no reward');
    check(await page.evaluate(()=>!Quests.mapMarkers(0).some(m=>m.quest==='slime_patrol')),'abandon clears tracked destinations');
    await visit(0,'gatekeeper'); await page.locator('#npc-quests [data-quest="slime_patrol"]').tap();
    await page.locator('#npc-quests [data-action="accept"]').tap();
    await page.locator('#npc-dialogue').waitFor({state:'hidden'});
    check((await ledger('slime_patrol')).counts[0]===0,'retaking starts with zero kill progress');
    await debug(page,{op:'set_level',level:2});
    await debug(page,{op:'quest',id:'es_01',action:'complete'});
    await visit(0,'smith'); await page.locator('#npc-quests [data-quest="es_01"]').tap();
    const reward=page.locator('#npc-quests .quest-reward-icon[data-action="claim"]').first();
    await reward.tap(); await reward.tap();
    await page.waitForFunction(()=>Field.hero.quests.some(q=>q.id==='es_go_02'&&!q.claimed));
    check((await ledger('es_01')).claimed && await page.evaluate(()=>Field.hero.level<7),'claim immediately gives handoff below next chapter level');
    await page.evaluate(()=>{City.close();Quests.show();});
    check(await page.locator('#quest-list .quest-entry[open]').count()===0,'opening journal folds every quest again');
    const handoff=page.locator('#quest-list .quest-entry[data-quest="es_go_02"]');
    await handoff.locator(':scope > summary').tap();
    check((await handoff.textContent()).includes('level 7') && (await handoff.textContent()).includes('Kael'),'handoff names next giver and level');
    await handoff.getByRole('button',{name:'Track quest',exact:true}).tap();
    check(await page.evaluate(()=>Quests.mapMarkers(1).some(m=>m.quest==='es_go_02'&&m.state==='tracked')),'handoff tracks real next giver across zones');
    await visit(1,'crags_scout');
    check(await page.locator('#npc-quests .gossip-row[data-quest="es_02"]').count()===0 && !(await ledger('es_go_02')).claimed,'visiting early keeps handoff and next chapter level gate');
    await page.keyboard.press('Escape'); await debug(page,{op:'set_level',level:7});
    await visit(1,'crags_scout'); await page.locator('#npc-quests .gossip-row[data-quest="es_02"]').tap();
    await page.locator('#npc-quests [data-action="accept"]').tap();
    await page.locator('#npc-dialogue').waitFor({state:'hidden'});
    await page.waitForFunction(()=>Field.hero.quests.some(q=>q.id==='es_go_02'&&q.claimed)&&Field.hero.quests.some(q=>q.id==='es_02'&&!q.claimed));
    check(true,'accepting next chapter resolves handoff without a gap');
    await page.evaluate(()=>Quests.show());
    const completed=page.locator('.quest-completed'); await completed.locator(':scope > summary').tap();
    const old=completed.locator('.quest-entry[data-quest="es_01"]');
    check(!await old.evaluate(n=>n.open),'completed chapters also start folded');
    await old.locator(':scope > summary').tap();
    await old.locator('.quest-memories').waitFor({state:'attached'});
    check(await old.locator('.quest-memories').count()===1,'completed story retains recovered memories');
    await page.screenshot({path:`${out}/quest-journal-${width}x${height}.png`});
    await page.context().close();
  }
};
module.exports=suite;
if(require.main===module)run([suite]).catch(e=>{console.error(e);process.exitCode=1;});
