// Real private WebSocket quest, mount rules, second-player view and saved ownership.
const assert=require('node:assert/strict');
const {TestWorld,actionSchema}=require('../scripts/testing/driver.cjs');
const w=new TestWorld(),bot='ReefRider',watcher='ReefWitness';
(async()=>{
  actionSchema.parse({type:'select_mount',mount:'seahorse'});
  await w.start();
  await w.connect({bot,class:'warrior'});await w.connect({bot:watcher,class:'mage'});
  await w.debug(bot,{op:'set_level',level:35});
  await w.debug(bot,{op:'quest',id:'deep_welcome',action:'finish'});
  const here={zone:8,x:83,y:199.2};
  await w.debug(bot,{op:'teleport',...here});await w.debug(watcher,{op:'teleport',zone:8,x:84,y:201});
  await w.waitFor(()=>!w.player(bot).cutscene,15000,'dive complete');
  await w.action(bot,{type:'interact',npc:'deep_healer',offer:'quest:accept:deep_seahorse'});
  await w.waitFor(()=>w.player(bot).quests.some(q=>q.id==='deep_seahorse'));
  await w.debug(bot,{op:'give_item',item:'fish_pier_sprat',quantity:10});
  await w.action(bot,{type:'interact',npc:'deep_healer',offer:'quest:claim:deep_seahorse'});
  assert(!w.player(bot).mounts.includes('seahorse'));
  await w.debug(bot,{op:'give_item',item:'fish_saltby_herring',quantity:5});
  await w.advance(650);
  await w.action(bot,{type:'interact',npc:'deep_healer',offer:'quest:claim:deep_seahorse'});
  await w.waitFor(()=>w.player(bot).mounts.includes('seahorse'));
  assert(!w.player(bot).inventory.some(i=>['fish_pier_sprat','fish_saltby_herring'].includes(i.item)));
  await w.action(bot,{type:'select_mount',mount:'seahorse'});
  await w.action(bot,{type:'mount',mounted:true});
  await w.waitFor(()=>w.player(bot).mounted);
  await w.waitFor(()=>w.views.get(watcher).players.some(p=>p.id===w.player(bot).id&&p.mount==='seahorse'&&p.mounted));
  await w.disconnect(bot);await w.connect({bot});
  assert(w.player(bot).mounts.includes('seahorse'));assert.equal(w.player(bot).mount,'seahorse');
  await w.restart();
  assert(w.player(bot).mounts.includes('seahorse'));assert.equal(w.player(bot).mount,'seahorse');
  assert(w.player(bot).quests.some(q=>q.id==='deep_seahorse'&&q.claimed));
  await w.debug(bot,{op:'teleport',zone:9,x:100,y:100});
  await w.action(bot,{type:'mount',mounted:true});await w.waitFor(()=>w.player(bot).mounted);
  await w.debug(bot,{op:'give_mount',mount:'horse'});
  await w.action(bot,{type:'select_mount',mount:'horse'});await w.waitFor(()=>!w.player(bot).mounted);
  await w.action(bot,{type:'mount',mounted:true});
  await w.waitFor(()=>w.events.some(e=>e.type==='error'&&e.text==='Only a seahorse can be ridden underwater.'));
  await w.debug(bot,{op:'teleport',zone:0,x:276,y:226});
  await w.waitFor(()=>!w.player(bot).cutscene,15000,'surface complete');
  await w.action(bot,{type:'select_mount',mount:'seahorse'});
  await w.action(bot,{type:'mount',mounted:true});
  await w.waitFor(()=>w.events.some(e=>e.type==='error'&&e.text==='A seahorse can be ridden only underwater.'));
  assert(!w.player(bot).mounted);
  await w.action(bot,{type:'select_mount',mount:'horse'});await w.action(bot,{type:'mount',mounted:true});
  await w.waitFor(()=>w.player(bot).mounted);
  console.log('Seahorse private protocol: real quest claim, fish costs, public rider, both underwater zones, land restrictions, reconnect and private restart pass');
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{await w.stop();});
