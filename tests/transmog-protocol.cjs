// Real private WebSocket controller, two players, reconnect and process restart; no browser or live database.
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path');
const { TestWorld, delay } = require('../scripts/testing/driver.cjs');
const root = path.resolve(__dirname, '..'), map = JSON.parse(fs.readFileSync(path.join(root, 'world/map.txt'))), items = JSON.parse(fs.readFileSync(path.join(root, 'world/items.txt')));
const w = new TestWorld(); w.levelSpread = 0;
const npc = map.zones[3].npcs.find(n => n.id === 'city_transmog');
const costume = items.find(i => i.kind === 'armor' && i.class === 'warrior' && i.requiredLevel === 95 && i.rarity === 'uncommon');
const head = items.find(i => i.kind === 'headgear' && i.class === 'warrior' && i.requiredLevel === 1);
const upgrade = items.find(i => i.kind === 'armor' && i.class === 'warrior' && i.requiredLevel === 5 && i.rarity === 'uncommon');
let checks = 0; const check = (v, m) => { assert(v, m); checks++; };
const send = async (bot, packet) => { await delay(40); w.bots.get(bot).socket.send(JSON.stringify(packet)); };
const change = choices => send('Owner', { type: 'transmogrify', npc: npc.id, changes: choices });
const wait = (p, label) => w.waitFor(p, 15000, label);
(async () => {
  await w.start(); await w.connect({ bot: 'Owner', class: 'warrior' }); await w.connect({ bot: 'Watcher', class: 'mage' });
  await w.debug('Owner', { op: 'teleport', zone: 4, x: npc.x, y: npc.y });
  await w.debug('Watcher', { op: 'teleport', zone: 4, x: npc.x + 2, y: npc.y });
  await w.debug('Owner', { op: 'set_gold', gold: 10_000 });
  for (const i of [costume, head]) await w.debug('Owner', { op: 'give_item', item: i.id, quantity: 1 });
  await send('Owner', { type: 'equip', slots: { headgear: head.id } });
  await wait(() => w.player('Owner').equipment.headgear === head.id, 'head worn');
  await w.debug('Owner', { op: 'take_item', item: costume.id, quantity: 1 });
  await send('Owner', { type: 'interact', npc: npc.id });
  const first = await wait(() => w.events.find(e => e.bot === 'Owner' && e.type === 'dialogue' && e.npc.id === npc.id), 'wardrobe dialogue');
  check(first.wardrobe.includes(costume.id), 'taking the item away preserves its wardrobe unlock');
  check(first.transmogPrice === 500 && first.look.class === 'warrior', 'authoritative level-one fee and actual equipment look');
  const before = w.player('Owner'), actual = before.equippedLook.warriorArmor;
  await change({ chest: costume.id, headgear: 'hide' });
  await wait(() => w.player('Owner').transmogs.chest === costume.id, 'apply cosmetics');
  const dressed = w.player('Owner');
  check(dressed.gold === 9000, 'two slots charge exactly ten silver');
  check(dressed.look.warriorArmor === costume.variant && dressed.look.head === 'none', 'visible look carries armor appearance and hide');
  check(dressed.equippedLook.warriorArmor === actual && dressed.attack === before.attack && dressed.defense === before.defense, 'actual equipment and stats remain unchanged');
  check(JSON.stringify(dressed.inventory) === JSON.stringify(before.inventory), 'applying appearances does not alter inventory');
  const visible = await wait(() => w.views.get('Watcher')?.players.find(p => p.id === dressed.id && p.look.warriorArmor === costume.variant), 'observer sees appearance');
  check(!('wardrobe' in visible) && !('equippedLook' in visible) && !('transmogs' in visible), 'observer snapshots contain no private wardrobe or real equipment data');
  await send('Watcher', { type: 'inspect', id: dressed.id });
  const inspect = await wait(() => w.events.find(e => e.bot === 'Watcher' && e.type === 'inspect' && e.ok), 'Inspect reply');
  check(inspect.transmogs.chest === costume.id && inspect.transmogs.headgear === 'hide', 'Inspect exposes active appearances');
  check(inspect.slots.find(s => s.slot === 'chest').item !== costume.id && inspect.look.warriorArmor === costume.variant, 'Inspect keeps actual item data alongside visible look');
  check(!('wardrobe' in inspect) && !('gold' in inspect), 'Inspect does not disclose collection or purse');
  const eventCount = w.events.length;
  await change({ headgear: 'real', hands: 'unknown-item' });
  await wait(() => w.events.slice(eventCount).some(e => e.bot === 'Owner' && e.type === 'error'), 'refuse bad batch');
  await delay(150);
  check(w.player('Owner').gold === 9000 && w.player('Owner').transmogs.headgear === 'hide', 'invalid batch leaves money and every chosen slot unchanged');
  await w.debug('Owner', { op: 'set_level', level: 5 });
  await w.debug('Owner', { op: 'give_item', item: upgrade.id, quantity: 1 });
  await send('Owner', { type: 'equip', slots: { chest: upgrade.id } });
  await wait(() => w.player('Owner').equippedLook.warriorArmor === upgrade.variant, 'upgrade real armor');
  check(w.player('Owner').look.warriorArmor === costume.variant, 'upgrading actual armor preserves the slot appearance');
  await send('Owner', { type: 'equip', slots: { chest: 'none' } });
  await wait(() => w.player('Owner').equippedLook.warriorArmor === 'none', 'unequip real armor');
  check(w.player('Owner').look.warriorArmor === 'none' && w.player('Owner').transmogs.chest === costume.id, 'empty slot is bare while saving its choice');
  await send('Owner', { type: 'equip', slots: { chest: upgrade.id } });
  await wait(() => w.player('Owner').look.warriorArmor === costume.variant, 're-equip restored cosmetic');
  await w.disconnect('Owner'); await w.connect({ bot: 'Owner' });
  check(w.player('Owner').transmogs.chest === costume.id && w.player('Owner').gold === 9000, 'reconnect preserves choices without another fee');
  await w.restart();
  check(w.player('Owner').look.warriorArmor === costume.variant && w.player('Owner').transmogs.headgear === 'hide' && w.player('Owner').gold === 9000, 'private process restart preserves appearance and purse');
  await w.debug('Owner', { op: 'teleport', zone: 4, x: npc.x, y: npc.y });
  await w.debug('Owner', { op: 'set_gold', gold: 0 });
  await change({ chest: 'real', headgear: 'real' });
  await wait(() => !w.player('Owner').transmogs.chest, 'free revert');
  check(w.player('Owner').gold === 0 && w.player('Owner').look.warriorArmor === upgrade.variant && w.player('Owner').look.head === head.variant, 'free revert restores actual appearances at zero purse');
  const receipt = { checks, snapshots: w.snapshotsChecked, assertions: 'wardrobe/apply/stats/privacy/Inspect/atomicity/upgrade/unequip/reconnect/restart/free-revert', artifacts: w.runDir };
  fs.writeFileSync(path.join(w.runDir, 'transmog-protocol.json'), JSON.stringify(receipt, null, 2) + '\n');
  console.log(`Transmogrify protocol: ${JSON.stringify(receipt)}`);
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => { await w.stop(); });
