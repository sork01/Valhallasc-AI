// Real private service flow; mutation serves the city module from before the workshop existed.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {execFileSync}=require('node:child_process');
const {chromium}=require('./lib/playwright.cjs');
const {TestWorld}=require('../scripts/testing/driver.cjs');
const root=path.resolve(__dirname,'..');
const w=new TestWorld();let browser;
(async()=>{
  await w.start();browser=await chromium.launch({headless:true,args:['--disable-gpu']});
  const page=await browser.newPage({viewport:{width:1280,height:800},reducedMotion:'reduce'});
  if(process.env.MUTATE==='1')await page.route('**/city.js',r=>r.fulfill({contentType:'application/javascript',body:execFileSync('git',['show','97f75da7:client/city.js'],{cwd:root,encoding:'utf8'})}));
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(()=>localStorage.setItem('valhallasc.save.v1',JSON.stringify({lang:'en',sound:false,char:null,draft:null})));
  await page.goto(w.url);await page.locator('#start').click();await page.locator('#login-guest').click();
  await page.locator('#cls-warrior').click();await page.locator('#name').fill('RodsmithUI');await page.locator('#go').click({timeout:60000});
  await page.waitForFunction(()=>Online.connected&&!!Field.warriorSprites,null,{timeout:60000});
  const debug=async command=>{
    const ref=Math.floor(Math.random()*1e9);await page.evaluate(({command,ref})=>Online.send({type:'debug',ref,command}),{command,ref});
  };
  await debug({op:'set_level',level:10});await debug({op:'set_gold',gold:1000});
  const npc=JSON.parse(fs.readFileSync(path.join(root,'world/map.txt'))).npcs.find(n=>n.id==='fisher_meadow_0');
  await debug({op:'teleport',zone:0,x:npc.x,y:npc.y});
  await page.waitForFunction(n=>Field.hero.level===10&&Math.hypot(Field.hero.x-n.x,Field.hero.y-n.y)<1,npc);
  await page.evaluate(()=>Online.send({type:'interact',npc:'fisher_meadow_0'}));
  await page.locator('[data-view="fisher"]').waitFor({timeout:5000});
  assert.equal(await page.locator('#npc-offers [data-offer^="cook:"]').count(),0,'recipes grouped behind workshop');
  await page.locator('[data-view="buy"]').click();
  await page.locator('#merchant-stock [data-offer="buy_twig_rod"]').click();
  await page.waitForFunction(()=>Inventory.bagQuantity('rod_twig_rod')===1);
  await page.waitForFunction(()=>Field.hero.gold===950);
  assert.equal(await page.evaluate(()=>Field.hero.gold),950,'Twig Rod costs 50');
  await page.locator('#npc-back').click();await page.locator('[data-view="fisher"]').click();
  const craft=page.locator('#npc-inventory [data-offer="rod:2"]');
  assert(await craft.isDisabled(),'missing materials disable crafting');
  await page.locator('#npc-x').click();
  await debug({op:'give_item',item:'fish_pier_sprat',quantity:6});await debug({op:'give_item',item:'slime_gel',quantity:1});
  await page.waitForFunction(()=>Inventory.bagQuantity('fish_pier_sprat')===6&&Inventory.bagQuantity('slime_gel')===1);
  await page.evaluate(()=>Online.send({type:'interact',npc:'fisher_meadow_0'}));await page.locator('[data-view="fisher"]').click();
  assert(!(await craft.isDisabled()));await page.waitForTimeout(600);await craft.click();
  await page.waitForFunction(()=>Inventory.bagQuantity('rod_willow_rod')===1);
  assert.equal(await page.evaluate(()=>Inventory.bagQuantity('rod_twig_rod')),0);
  assert.equal(await page.evaluate(()=>Inventory.bagQuantity('fish_pier_sprat')),1);
  assert(await craft.isDisabled(),'after dialogue refresh recipe reflects spent ingredients');
  assert(await page.locator('#npc-back').isVisible(),'workshop remains open after purchase');
  // Allow the shared service rate limit to expire, then cook the remaining raw fish.
  await page.waitForTimeout(600);
  await page.locator('#npc-inventory [data-offer="cook:fish_pier_sprat"]').click();
  await page.waitForFunction(()=>Inventory.bagQuantity('dish_shore_grill')===1);
  assert.equal(await page.evaluate(()=>Inventory.bagQuantity('fish_pier_sprat')),0);
  // The game requires landscape on phones; portrait displays its rotation cover.
  await page.setViewportSize({width:844,height:390});
  const phoneRecipe=page.locator('#npc-inventory [data-offer="rod:2"]');
  await phoneRecipe.scrollIntoViewIfNeeded();
  assert(await phoneRecipe.isVisible(),'landscape phone recipe is visible');
  const phoneRect=await phoneRecipe.boundingBox();
  assert(phoneRect&&phoneRect.x>=0&&phoneRect.y>=0&&phoneRect.x+phoneRect.width<=844&&phoneRect.y+phoneRect.height<=390,'phone recipe fits inside the visible screen');
  assert.equal(await page.locator('.gossip-parchment').evaluate(el=>el.scrollWidth<=el.clientWidth+1),true,'landscape phone parchment has no horizontal overflow');
  await page.screenshot({path:path.join(w.runDir,'fisher-workshop-phone.png')});
  await page.setViewportSize({width:600,height:390});
  await phoneRecipe.scrollIntoViewIfNeeded();
  assert.equal(await page.locator('.gossip-parchment').evaluate(el=>el.scrollWidth<=el.clientWidth+1),true,'small landscape phone has no horizontal overflow');
  assert(await phoneRecipe.evaluate(el=>{const r=el.getBoundingClientRect();return document.elementFromPoint(r.x+r.width/2,r.y+r.height/2)===el;}),'phone recipe is not covered by another screen');
  await page.screenshot({path:path.join(w.runDir,'fisher-workshop-small-phone.png')});
  await page.setViewportSize({width:1280,height:800});
  await page.screenshot({path:path.join(w.runDir,'fisher-workshop.png')});
  await page.locator('#npc-back').click();assert(await page.locator('[data-view="fisher"]').isVisible());
  await page.locator('#npc-x').click();
  await page.screenshot({path:path.join(w.runDir,'fisher-scene.png')});
  assert.deepEqual(errors,[]);
  console.log('Fisher UI: purchase, ingredients, crafting, cooking, retained view, back/close and phone layout pass');
  console.log('Screenshots:',w.runDir);
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{await browser?.close();await w.stop();});
