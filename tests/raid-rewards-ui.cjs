// Rewards only, in a private world: actual equipment, tooltip, bar and persistence.
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {chromium}=require('./lib/playwright.cjs');
const {Client}=require('@modelcontextprotocol/sdk/client/index.js');
const {StdioClientTransport}=require('@modelcontextprotocol/sdk/client/stdio.js');
const root=path.resolve(__dirname,'..'),client=new Client({name:'raid-rewards-ui',version:'1'});
let browser,world,checks=0;
const check=(v,t)=>{assert.ok(v,t);checks++;};
const call=async(name,args={})=>{const r=await client.callTool({name,arguments:args});assert.ok(!r.isError,JSON.stringify(r.content));return r.structuredContent;};
(async()=>{
 await client.connect(new StdioClientTransport({command:process.execPath,args:[path.join(root,'scripts/test-mcp.cjs')],cwd:root,stderr:'pipe',env:{...process.env}}));
 world=await call('start_world',{startLevel:99,levelSpread:0,godMode:true});
 browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>{if(!sessionStorage.getItem('raid-seeded')){sessionStorage.setItem('raid-seeded','1');localStorage.setItem('valhallasc.save.v1',JSON.stringify({lang:'en',sound:false}));}});
 await page.goto(world.url);await page.locator('#start').click();await page.locator('#login-guest').click();
 await page.locator('#name').fill('Forge Rewards');await page.locator('#go').click({timeout:60000});
 await page.waitForFunction(()=>Online.connected&&Field.hero,null,{timeout:60000});
 const debug=command=>page.evaluate(command=>Online.send({type:'debug',command}),command);
 const items=JSON.parse(fs.readFileSync(path.join(root,'world/items.txt'))).filter(i=>i.source==='chained_forge'&&(!i.class||i.class==='warrior'));
 for(const i of items)await debug({op:'give_item',item:i.id,quantity:i.kind==='accessory'?2:1,force:true});
 await page.waitForFunction(()=>Field.hero.inventory.some(i=>i.item==='chainforged_cloak'));
 const slots=Object.fromEntries(items.map(i=>[i.kind==='armor'?'chest':i.kind==='weapon'?'hands':i.kind==='accessory'?'accessory1':i.kind,i.id]));slots.accessory2='chainforged_accessory';
 await page.evaluate(slots=>Online.send({type:'equip',slots}),slots);
 await page.waitForFunction(()=>Field.hero.signatureWeapon==='chainforged_warrior_weapon'&&Field.hero.setCounts?.chained_forge===8);
 check(await page.evaluate(()=>Field.hero.look.cloak==='chainforged_cloak'),'The tenth slot equips the original raid cloak');
 check(await page.evaluate(()=>Field.hero.equipment.accessory1===Field.hero.equipment.accessory2),'Both ring slots have a raid copy');
 const originalSlots=await page.evaluate(()=>Online.skillSlots);
 await page.keyboard.press('k');await page.locator('#skills-panel').waitFor({state:'visible'});
 check((await page.locator('#skill-library [data-skill="earthshatter"] b').textContent())==='Slagshatter','The original skill is replaced in its existing library/bar id');
 check(await page.locator('#skillbar-slots button').count()===12,'The bar remains twelve slots');
 await page.keyboard.press('Escape');await page.keyboard.press('e');await page.locator('#equipment').waitFor({state:'visible'});
 await page.waitForFunction(async()=>{
  const spr=await WarriorSprite.load(Field.hero.look);
  await Promise.all(Object.entries(spr.equipment).filter(([,a])=>a&&a!=='none').map(([slot,a])=>spr.source.ensure(slot+'_'+a)));
  spr.cache.clear();const expected=document.createElement('canvas');expected.width=320;expected.height=420;
  const g=expected.getContext('2d');g.translate(160,365);spr.draw(g,{fx:1,fy:1,walk:0},0,2.8);
  const a=expected.getContext('2d').getImageData(0,0,320,420).data,b=document.getElementById('equipmentcv').getContext('2d').getImageData(0,0,320,420).data;
  return a.every((v,i)=>v===b[i]);
 },null,{timeout:60000});
 check(true,'The Character preview redraws with every fitted layer after lazy decoding');
 const icon=page.locator('#equipped-slots [data-slot="hands"] .gear-icon');
 const hands=await icon.count()?icon:page.locator('[data-slot="hands"] .gear-icon').first();
 await hands.hover();await page.locator('#item-tooltip').waitFor({state:'visible'});
 const tooltip=await page.locator('#item-tooltip').textContent();
 check(tooltip.includes('Chainsplitter')&&tooltip.includes('Replaces Earthshatter with Slagshatter'),'Tooltip names the weapon and both skill names');
 check(tooltip.includes('Chainforged · 8/8')&&!tooltip.includes('chained_forge'),'The set has its display name');
 check(tooltip.includes('once every 3 seconds')&&tooltip.includes('3%'),'Tooltip explains cooldown and player cap');
 await page.screenshot({path:path.join(world.artifacts,'raid-rewards-equipped.png')});
 await page.evaluate(()=>Online.send({type:'equip',slots:{hands:'none'}}));
 await page.waitForFunction(()=>Field.hero.signatureWeapon===null);
 await page.keyboard.press('Escape');await page.keyboard.press('k');
 check((await page.locator('#skill-library [data-skill="earthshatter"] b').textContent())==='Earthshatter','Unequip restores the original skill name');
 check(await page.evaluate(old=>JSON.stringify(Online.skillSlots)===JSON.stringify(old),originalSlots),'Equip and unequip preserve all saved bar assignments');
 await page.keyboard.press('Escape');await page.evaluate(()=>Online.send({type:'equip',slots:{hands:'chainforged_warrior_weapon'}}));
 await page.waitForFunction(()=>Field.hero.signatureWeapon==='chainforged_warrior_weapon');
 await page.reload();await page.locator('#start').click();await page.locator('#login-guest').click();
 await page.waitForFunction(()=>Online.connected||!document.getElementById('scene-create').hidden,null,{timeout:60000});
 if(await page.locator('#scene-create').isVisible())await page.locator('#go').click({timeout:60000});
 await page.waitForFunction(()=>Online.connected&&Field.hero.signatureWeapon==='chainforged_warrior_weapon',null,{timeout:60000});
 check(await page.evaluate(()=>Field.hero.setCounts.chained_forge===8),'Saved gear reloads with the full set');
 const sw=await browser.newPage();await sw.addInitScript(()=>localStorage.setItem('valhallasc.save.v1',JSON.stringify({lang:'sv',sound:false})));await sw.goto(world.url);
 check(await sw.evaluate(()=>Locale.translate('Chainsplitter')==='Kedjeklyvaren'&&Locale.translate('Slagshatter')==='Slaggkross'),'Weapon and upgraded skill have hand-written Swedish');
 check(await sw.evaluate(()=>!Locale.translate(RaidRewards.tooltip({id:'chainforged_warrior_weapon'})).includes('Replaces')),'Composed weapon tooltip translates into Swedish');await sw.close();
 check(errors.length===0,JSON.stringify(errors));
 fs.writeFileSync(path.join(world.artifacts,'raid-rewards-ui.json'),JSON.stringify({passed:true,checks,errors},null,2));
 console.log(JSON.stringify({passed:true,checks,artifacts:world.artifacts}));
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{
 if(browser)await browser.close();if(world)try{await call('stop_world');}catch{}await client.close();
});
