#!/usr/bin/env python3
"""Export public bring-objective sources from the authoritative drop table.

Secret crosses and gate-key materials intentionally retain giver guidance.
Called by sync-world.cjs; --output permits private client validation.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def sources():
    world = json.loads((ROOT / 'world/map.txt').read_text())
    areas = [world, *world['zones']]
    body = (ROOT / 'server/src/items.rs').read_text().split('pub fn material(kind: &str)')[1].split('\npub fn ')[0]
    materials = {'green': 'slime_gel'}
    for kinds, material in re.findall(r'((?:"[^"]+"\s*\|\s*)*"[^"]+")\s*=>\s*"([^"]+)"', body):
        for kind in re.findall(r'"([^"]+)"', kinds):
            materials[kind] = material
    catalog = {}
    for path in (ROOT / 'world').glob('*.txt'):
        try:
            data = json.loads(path.read_text())
        except (json.JSONDecodeError, UnicodeDecodeError):
            continue
        if isinstance(data, list):
            for row in data:
                if isinstance(row, dict) and 'kind' in row and 'material' in row:
                    materials[row['kind']] = row['material']
                    catalog[row['kind']] = row
    targets = {o['target'] for area in areas for q in area.get('quests', [])
               for o in q['objectives'] if o['kind'] == 'bring'}
    # A quest-only item (scripts/quest_items.py) drops from the monsters of the material it is made from.
    source_of = {i['id']: i['questMaterial'] for i in json.loads((ROOT / 'world/items.txt').read_text()) if i.get('questMaterial')}
    out = {}
    for target in sorted(targets):
        points = []
        hidden = target.startswith(('hour_shard_', 'ember_shard_')) or target == 'ember_key'
        if not hidden:
            for zone, area in enumerate(areas):
                groups = {}
                for spawn in area.get('slimes', []):
                    kind = spawn['kind']
                    if (materials.get(kind) != source_of.get(target, target) or spawn.get('ambush')
                            or catalog.get(kind, {}).get('add') or kind == 'ember_firelord'):
                        continue
                    groups.setdefault(kind, []).append(spawn)
                for kind, spawns in groups.items():
                    # Keep real candidates: the client chooses the nearest pack from the hero's current position.
                    points.extend({'zone': zone, 'x': s['x'], 'y': s['y'], 'enemy': kind} for s in spawns)
                for npc in area.get('npcs', []):
                    if any(o.get('item') == target for o in npc.get('offers', [])):
                        points.append({'zone': zone, 'x': npc['x'], 'y': npc['y'], 'npc': npc['id']})
        out[target] = points
    return out


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'client/quest-sources.js')
    args = parser.parse_args()
    result = sources()
    args.output.write_text("'use strict';\n// Generated by scripts/quest_sources.py; do not edit.\nwindow.QUEST_SOURCES = "
                           + json.dumps(result, ensure_ascii=False, separators=(',', ':')) + ';\n')
    missing = [target for target, points in result.items() if not points]
    print(f'{len(result)} bring materials audited; giver fallback: {", ".join(missing)}')
