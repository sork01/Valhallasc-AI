#!/usr/bin/env python3
"""Derive which maps may roll treasure chests (docs/chests.md, CHEST-RULES).

A map is eligible when it has monsters (`slimes`). A map with `copies` is a dungeon: each running party copy rolls on
its own. Everything else with monsters is an open-world zone. Cities and enemy-free maps never roll.

    python3 scripts/chest_zones.py          # print the list
    python3 scripts/chest_zones.py --write  # rewrite docs/chest-eligibility.txt
    python3 scripts/chest_zones.py --check  # exit 1 when the file is stale
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "chest-eligibility.txt"


def derive():
    world = json.loads((ROOT / "world" / "map.txt").read_text())
    maps = [(0, world)] + [(i + 1, z) for i, z in enumerate(world["zones"])]
    open_zones, dungeons, never = [], [], []
    for number, z in maps:
        name = z.get("name", "?")
        count = len(z.get("slimes", []))
        lo, hi = (z.get("levels") or [0, 0])[:2] if z.get("levels") else (0, 0)
        if not count:
            never.append((number, name))
        elif z.get("copies"):
            dungeons.append((number, name, count, z["copies"], lo, hi))
        else:
            open_zones.append((number, name, count, lo, hi))
    return open_zones, dungeons, never


def render():
    open_zones, dungeons, never = derive()
    lines = [
        "# Generated by scripts/chest_zones.py from world/map.txt. Do not edit by hand.",
        f"open_zones {len(open_zones)}",
    ]
    lines += [f"  zone {n:>2} {name} (monsters {c}, levels {lo}-{hi})" for n, name, c, lo, hi in open_zones]
    lines.append(f"dungeons {len(dungeons)} (each party copy rolls separately; copies per dungeon shown)")
    lines += [
        f"  zone {n:>2} {name} (monsters {c}, copies {k}, levels {lo}-{hi})" for n, name, c, k, lo, hi in dungeons
    ]
    lines.append(f"never {len(never)} (no monsters)")
    lines += [f"  zone {n:>2} {name}" for n, name in never]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = render()
    if "--write" in sys.argv:
        OUT.write_text(text)
    elif "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("docs/chest-eligibility.txt is stale: run python3 scripts/chest_zones.py --write")
    else:
        print(text, end="")
