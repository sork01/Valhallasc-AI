#!/usr/bin/env python3
"""Merge the per-level outputs of duel-parallel.sh into docs/duel-report.md (PVP-DUEL-MATRIX)."""
import argparse
import json
import statistics
from collections import defaultdict
from pathlib import Path

CLASSES = ('warrior', 'mage', 'assassin', 'priest', 'hunter')
TITLE = {c: c.capitalize() for c in CLASSES}
CAP = 300.


def load(paths):
    rows = []
    for path in paths:
        data = json.loads(Path(path).read_text())
        if not data:
            raise ValueError(f'{path} has no duels')
        rows.extend(data)
    return rows


def fmt_time(seconds):
    return f'{seconds:.1f} s'


def points(rows, a):
    """Win points of class `a` (the pair's first class) over the rows: win 1, draw 0.5."""
    return sum(1. if r['winner'] == 'a' else 0.5 if r['winner'] == 'draw' else 0. for r in rows)


def rate_of(x, y, by_pair):
    """Win rate of class x against class y, pooled over the rows given (a list)."""
    rows = by_pair.get(tuple(sorted((x, y), key=CLASSES.index)), [])
    if not rows:
        return None
    first = CLASSES.index(x) <= CLASSES.index(y)
    p = points(rows, 'a') / len(rows)
    return p if first else 1. - p


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    ap.add_argument('--gear', default='the level\'s normal green progression gear')
    ap.add_argument('files', nargs='+')
    args = ap.parse_args()
    rows = load(args.files)
    levels = sorted({r['level'] for r in rows})
    by = defaultdict(list)  # (level, a, b) -> rows
    for r in rows:
        by[(r['level'], r['a'], r['b'])].append(r)
    pairs = [(a, b) for i, a in enumerate(CLASSES) for b in CLASSES[i:]]
    missing = [(l, a, b) for l in levels for a, b in pairs if (l, a, b) not in by]
    if missing:
        raise ValueError(f'missing cases: {missing[:5]}')

    out = []
    w = out.append
    runs_per_pair = sorted({len(v) for v in by.values()})
    w('# Duel matrix: every class against every class\n')
    w('Generated by `bash scripts/duel-parallel.sh` (`PVP-DUEL-MATRIX`) from real duels in isolated in-memory worlds; '
      'this report is input to later balancing and changes no game stat.\n')
    w('## Method\n')
    w('- Code under test: the real duel (`server/src/world/pvp.rs`): challenge and accept, the 25-tile ring, a blow '
      'that would take a duelist to 0 leaves 1 health and ends the duel, no loot, no XP. Harness: '
      '`server/src/world/duel_tests.rs`.')
    w(f'- Characters: both sides at the same level, in {args.gear} (no refinement, no set bonus, no potions or '
      'food), the even default attribute allocation, every skill and rank earned by the level. Same gear tier as the DPS report.')
    w('- **Skills hurt players in duels** (the damaging skills of `use_skill` and their bolts and dashes now resolve against the '
      'duel partner, the opposing arena team and flagged players through `pvp_hit` in `pvp.rs`; before 2026-10-20 only the basic '
      'attack could). A skill blow uses the same rules as the basic blow: defence is subtracted, damage is scaled by 0.25, '
      'shield and dodge apply, and a duelist stops at 1 health. A warrior gains rage from the damage it deals, as against monsters.')
    w('- **PvP rules in force** (all in `pvp.rs` and `use_skill`, PvP only; monsters are unaffected): every blow that lands on a player is scaled by '
      '`PVP_DAMAGE_SCALE` 0.5 on top of the monster scale of 0.25. Skills with a status: a **3 s stun** (no moving, attacking or casting) from '
      'Warrior Earthshatter (15 s cooldown), Assassin Knife Ring (14 s) and Hunter Rain of Arrows (12 s); a **3 s root** (no moving or dashing) from '
      'Mage Arcane Storm (15 s); a **heal cut of 50% for 10 s** (skill heals, lifesteal, potions, food, set heals) from Warrior Titan\'s Wrath (40 s), '
      'Assassin Thousand Cuts (28 s), Mage Starfall (36 s) and Hunter Arrow Storm (30 s). A status needs a blow that lands (a dodge or miss applies nothing), '
      'does not stack (the longer wins) and ends with the duel. **Healing is scaled by the same 0.5** for a player in a PvP fight (a blow dealt or taken in the last 10 s; '
      'it clears when the duel ends), or halving the damage would double what healing is worth. **A hunter\'s blows on players deal 35% more** (owner, 2026-10-20: +25%, then +10%). '
      '**A priest\'s own healing is scaled once more by 0.5** in a PvP fight (a quarter in all). '
      '**Mage Arcane Ward (28 s)** also soaks up the next 20% of the mage\'s maximum health in damage from players for 10 s.')
    w('- Rotation: **the mercenaries\' own code** (`World::ai_combat_at`, the body of `ai_combat`): every skill when ready, affordable and in '
      'reach, buffs when none is active and the foe is within 10 tiles, a heal below 55% health, no dashes. The harness only walks to '
      '90% of the class\'s reach (a mercenary\'s stand-off) and swings the basic attack (`PvpCommand::Attack`, reach 1.8 for the melee classes, '
      '8 for mage and hunter) whenever its cooldown allows. This is not the best rotation of `docs/best-rotations.md`. The caveats of the DPS report apply: '
      'the mercenaries\' code starves assassin and hunter of energy and never fires dashes (`DPS-ROTATION`), so their results are a floor.')
    w('- Start: 10 tiles apart on a flat clear line in Greenmeadow, the monsters of that zone removed. '
      'The pair is run in both orders (class A left with session 1, then right with session 2; session 1 acts first within '
      'a tick, so each class has that one-tick edge half the time). A mirror match (same class) is run on one order '
      'with twice the seeds; its figure is the share won by session 1.')
    w(f'- Seeds: {", ".join(str(n) for n in runs_per_pair)} duels per pair and level (crits, hit rolls, dodges and damage '
      'spread are random; seeds 1..n). A duel that has no winner after 300 s of game time is a draw and counts half a win.')
    w('- Numbers: win rate = (wins + half of draws) / duels. Time = seconds from accept to the last blow, over decided duels: '
      'median and the shortest to longest. Damage = health points taken off the other side by each source (the 1-health floor of a duel respected), '
      'from the server\'s own accounting. Casts = buff and heal casts, from the server\'s own count.')
    w('- Caveats: the figures describe two scripted players, not skilled play: no kiting, no dashes or escapes, no potions, no '
      'target-ground meteor aiming (a meteor lands on the nearest foe in range), no skill choice by situation. A human warrior closing on a mage, '
      'or a hunter running away, would shift the result. Gear is the level\'s green set; purple/orange gear, set bonuses and rebirth perks '
      'are not modelled. The mercenaries\' code stands still at 90% of reach, so a ranged class never kites a melee one.\n')

    # --- overall ---
    def pooled(level=None):
        res = {}
        for x in CLASSES:
            tot = n = 0.
            for y in CLASSES:
                if x == y:
                    continue
                key = tuple(sorted((x, y), key=CLASSES.index))
                rs = [r for l in ([level] if level else levels) for r in by[(l, *key)]]
                p = points(rs, 'a') / len(rs)
                p = p if x == key[0] else 1. - p
                tot += p * len(rs)
                n += len(rs)
            res[x] = tot / n
        return res

    overall = pooled()
    w('## Summary\n')
    order = sorted(CLASSES, key=lambda c: -overall[c])
    w('Win rate against the four other classes (all levels pooled): ' +
      ', '.join(f'**{TITLE[c]}** {overall[c]*100:.0f}%' for c in order) + '.\n')
    mirrors = {c: [r for r in rows if r['a'] == c and r['b'] == c] for c in CLASSES}
    w('Mirror matches (the share won by session 1, which acts first within a tick; 50% means no edge): ' + ', '.join(
        f'{TITLE[c]} {points(rs, "a")/len(rs)*100:.0f}%' for c, rs in mirrors.items()) + '.\n')
    drawn = defaultdict(list)
    for r in rows:
        if r['winner'] == 'draw':
            drawn[(r['a'], r['b'])].append(r['level'])
    if drawn:
        w('Duels that reached the 300 s cap (draws): ' + '; '.join(
            f'{TITLE[a]} v {TITLE[b]} at level {", ".join(str(l) for l in sorted(set(ls)))} ({len(ls)} duels)'
            for (a, b), ls in sorted(drawn.items())) + '.\n')
    w('| Level | ' + ' | '.join(TITLE[c] for c in CLASSES) + ' | Order |')
    w('| ---: |' + ' ---: |' * len(CLASSES) + ' --- |')
    prev = None
    flips = []
    for l in levels:
        p = pooled(l)
        o = sorted(CLASSES, key=lambda c: -p[c])
        # ties broken by the more stable class name order, which is fine for a display
        w(f'| {l} | ' + ' | '.join(f'{p[c]*100:.0f}%' for c in CLASSES) + ' | ' +
          ' > '.join(TITLE[c] for c in o) + ' |')
        if prev is not None and o != prev[1]:
            changed = [TITLE[c] for i, c in enumerate(o) if prev[1].index(c) != i]
            flips.append((prev[0], l, changed))
        prev = (l, o)
    w('')
    if flips:
        w('Where the order changes between neighbouring levels: ' + '; '.join(
            f'{a} to {b} ({", ".join(ch)} move)' for a, b, ch in flips) + '.\n')
    else:
        w('The order of the classes does not change between levels.\n')

    # --- pooled grid ---
    w('## Class against class, all levels pooled\n')
    w('Row class\'s win rate against the column class (draws count half); the diagonal is the share won by session 1 in the mirror match.\n')
    w('| | ' + ' | '.join(TITLE[c] for c in CLASSES) + ' |')
    w('| --- |' + ' ---: |' * len(CLASSES))
    for x in CLASSES:
        cells = []
        for y in CLASSES:
            key = tuple(sorted((x, y), key=CLASSES.index))
            rs = [r for l in levels for r in by[(l, *key)]]
            p = points(rs, 'a') / len(rs)
            cells.append(f'{(p if x == key[0] else 1. - p)*100:.0f}%')
        w(f'| **{TITLE[x]}** | ' + ' | '.join(cells) + ' |')
    w('')

    # --- per level ---
    w('## By level\n')
    for l in levels:
        w(f'### Level {l}\n')
        w('Win rate of the row class against the column class:\n')
        w('| | ' + ' | '.join(TITLE[c] for c in CLASSES) + ' |')
        w('| --- |' + ' ---: |' * len(CLASSES))
        for x in CLASSES:
            cells = []
            for y in CLASSES:
                key = tuple(sorted((x, y), key=CLASSES.index))
                rs = by[(l, *key)]
                p = points(rs, 'a') / len(rs)
                cells.append(f'{(p if x == key[0] else 1. - p)*100:.0f}%')
            w(f'| **{TITLE[x]}** | ' + ' | '.join(cells) + ' |')
        w('')
        w('| Duel | Duels | A wins | B wins | Draws | A win rate | Median time | Shortest to longest | A damage share | Casts A / B (per duel) | Draw: health left A / B |')
        w('| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |')
        for a, b in pairs:
            rs = by[(l, a, b)]
            aw = sum(r['winner'] == 'a' for r in rs)
            bw = sum(r['winner'] == 'b' for r in rs)
            dr = len(rs) - aw - bw
            times = sorted(r['seconds'] for r in rs if r['winner'] != 'draw')
            med = fmt_time(statistics.median(times)) if times else '-'
            span = f'{fmt_time(times[0])} to {fmt_time(times[-1])}' if times else '-'
            da = sum(r['sides'][0]['damage'] for r in rs)
            db = sum(r['sides'][1]['damage'] for r in rs)
            share = f'{da/(da+db)*100:.0f}%' if da + db else '-'
            ca = sum(sum(r['sides'][0]['casts'].values()) for r in rs) / len(rs)
            cb = sum(sum(r['sides'][1]['casts'].values()) for r in rs) / len(rs)
            draws = [r for r in rs if r['winner'] == 'draw']
            left = (f'{statistics.mean(r["sides"][0]["hpLeft"] for r in draws)*100:.0f}% / '
                    f'{statistics.mean(r["sides"][1]["hpLeft"] for r in draws)*100:.0f}%') if draws else '-'
            label = f'{TITLE[a]} v {TITLE[b]}' if a != b else f'{TITLE[a]} mirror (A = session 1)'
            w(f'| {label} | {len(rs)} | {aw} | {bw} | {dr} | {points(rs, "a")/len(rs)*100:.0f}% | {med} | {span} | '
              f'{share} | {ca:.1f} / {cb:.1f} | {left} |')
        w('')

    # --- sources ---
    w('## Where the damage comes from\n')
    w('Share of each class\'s damage by source, pooled over all its duels at the level (basic attack, then the three biggest skills):\n')
    w('| Level | ' + ' | '.join(TITLE[c] for c in CLASSES) + ' |')
    w('| ---: |' + ' --- |' * len(CLASSES))
    for l in levels:
        cells = []
        for c in CLASSES:
            tot = defaultdict(float)
            for r in rows:
                if r['level'] != l:
                    continue
                for slot, cls in (('a', r['a']), ('b', r['b'])):
                    if cls != c:
                        continue
                    for k, v in r['sides'][0 if slot == 'a' else 1]['sources'].items():
                        tot[k] += v['damage']
            total = sum(tot.values())
            if not total:
                cells.append('-')
                continue
            skills = sorted(((k, v) for k, v in tot.items() if k != 'basic'), key=lambda kv: -kv[1])[:3]
            cells.append(f'basic {tot["basic"]/total*100:.0f}%; ' + ', '.join(f'{k} {v/total*100:.0f}%' for k, v in skills))
        w(f'| {l} | ' + ' | '.join(cells) + ' |')
    w('')

    # --- duration ---
    w('## How long a duel takes\n')
    w('Median seconds of a decided duel, all pairs of the level, shortest and longest pair median:\n')
    w('| Level | Median | Shortest pair | Longest pair | Draws |')
    w('| ---: | ---: | --- | --- | ---: |')
    for l in levels:
        med_by_pair = {}
        times = []
        draws = 0
        for a, b in pairs:
            rs = by[(l, a, b)]
            ts = [r['seconds'] for r in rs if r['winner'] != 'draw']
            draws += len(rs) - len(ts)
            times += ts
            if ts:
                med_by_pair[(a, b)] = statistics.median(ts)
        lo = min(med_by_pair, key=med_by_pair.get)
        hi = max(med_by_pair, key=med_by_pair.get)
        w(f'| {l} | {fmt_time(statistics.median(times))} | {TITLE[lo[0]]} v {TITLE[lo[1]]} {fmt_time(med_by_pair[lo])} | '
          f'{TITLE[hi[0]]} v {TITLE[hi[1]]} {fmt_time(med_by_pair[hi])} | {draws} |')
    w('')

    Path(args.out).write_text('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
