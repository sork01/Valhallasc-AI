#!/usr/bin/env python3
"""Zone-shape preview (TODO SHAPE-PREVIEW). Read-only: never edits world/map.txt.

Takes the traced atlas outlines (scripts/atlas_geography.generate(), the same data
that gives the 47 live routes), scales them to tiles under a chosen scale rule and
overlays the CURRENT layout (north up, no rotation) so the owner can see what a
shape would cost. Old content is mapped by stretching the old square onto the new
bounding box; fixed footprints (city rectangles) are drawn at their TRUE tile size.

  python3 scripts/zone_shapes_preview.py [--out DIR] [--rule median|total|nofloor]
Writes valhallasc-shape-*.png, valhallasc-shape-table.md and a json summary.
"""
import argparse
import json
import math
import statistics
import sys
from collections import defaultdict
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
import atlas_geography  # noqa: E402

FONT = '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'
FONTB = '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf'
PNG = ROOT / 'client/assets/world-atlas-painted.png'
NEIGHBOUR_COLOURS = ['#ff6b6b', '#ffd93d', '#6bcB77', '#4d96ff', '#c77dff', '#ff9f1c', '#2ec4b6', '#f15bb5',
                     '#9b5de5', '#00bbf9', '#fee440', '#8ac926']


def font(size, bold=False):
    return ImageFont.truetype(FONTB if bold else FONT, size)


def area(p):
    return abs(sum(p[i][0]*p[(i+1) % len(p)][1]-p[(i+1) % len(p)][0]*p[i][1] for i in range(len(p))))/2


def inside(pt, poly):
    x, y = pt
    c = False
    for i in range(len(poly)):
        (x1, y1), (x2, y2) = poly[i], poly[(i+1) % len(poly)]
        if (y1 > y) != (y2 > y) and x < (x2-x1)*(y-y1)/(y2-y1)+x1:
            c = not c
    return c


def seg_dist(p, a, b):
    ax, ay = a
    bx, by = b
    dx, dy = bx-ax, by-ay
    t = 0 if dx == dy == 0 else max(0, min(1, ((p[0]-ax)*dx+(p[1]-ay)*dy)/(dx*dx+dy*dy)))
    return math.hypot(p[0]-(ax+t*dx), p[1]-(ay+t*dy))


def chain_dist(p, edges):
    return min((seg_dist(p, a, b) for a, b in edges), default=None)


def city_fits_at(poly, s, cw, ch):
    """True if a cw x ch tile rectangle fits wholly inside the outline scaled by s (tiles per atlas px)."""
    x0 = min(q[0] for q in poly)
    y0 = min(q[1] for q in poly)
    pts = [((q[0]-x0)*s, (q[1]-y0)*s) for q in poly]
    W = math.ceil(max(p[0] for p in pts))+2
    H = math.ceil(max(p[1] for p in pts))+2
    m = Image.new('1', (W, H))
    ImageDraw.Draw(m).polygon(pts, fill=1)
    px = m.load()
    ok = lambda x, y: 0 <= int(x) < W and 0 <= int(y) < H and px[int(x), int(y)]
    for yy in range(0, H, 2):
        for xx in range(0, W, 2):
            if all(ok(xx+cw*fx, yy+ch*fy) for fx in (0, .25, .5, .75, 1) for fy in (0, .25, .5, .75, 1)):
                return True
    return False


def city_min_scale(poly, base, cw, ch):
    s = base
    while not city_fits_at(poly, s, cw, ch) and s < base*8:
        s *= 1.04
    return s


def write_table(out):
    runs = {r: json.loads((out/f'summary-{r}.json').read_text()) for r in ('median', 'total', 'nofloor')}
    by = {r: {z['zone']: z for z in d['zones']} for r, d in runs.items()}
    L = ['# Zone shape preview: sizes under three scale rules', '',
         f"Generated by `scripts/zone_shapes_preview.py`. k = tiles per atlas pixel: median {runs['median']['k']:.3f}, "
         f"total-area {runs['total']['k']:.3f}. `nofloor` = median k, but no zone's outline area may drop below its current "
         f"area and the city footprint must fit (a deviation from strict proportion).", '',
         '| zone | old | median bbox | x area | total bbox | x area | no-shrink bbox | x area | city (true size) | min k for city | neighbours |',
         '|---|---|---|---|---|---|---|---|---|---|---|']
    for z, a in by['median'].items():
        b, c = by['total'][z], by['nofloor'][z]
        city = a['city']
        L.append(f"| {z} {a['name']} | {a['old']}x{a['old']} | {a['new'][0]}x{a['new'][1]} | {a['ratio']} | "
                 f"{b['new'][0]}x{b['new'][1]} | {b['ratio']} | {c['new'][0]}x{c['new'][1]} | {c['ratio']} | "
                 f"{(str(city['w'])+'x'+str(city['h'])+(' fits' if city['fits_anywhere'] else ' CANNOT FIT')) if city else '-'} | "
                 f"{city['min_scale_to_fit'] if city else '-'} | {len(a['neighbours'])} |")
    L += ['', '## Content outside the outline (median rule, old square stretched onto the new bbox)', '',
          '| zone | spawns | NPCs | places | portals: border / dist to shared border (tiles) | edges shared/coast/land |',
          '|---|---|---|---|---|---|']
    for z, a in by['median'].items():
        o = a['outside']
        pt = ', '.join(f"{pid}->{to}: {d}" for pid, to, d in a['portals'])
        L.append(f"| {z} {a['name']} | {o['slimes'][0]}/{o['slimes'][1]} | {o['npcs'][0]}/{o['npcs'][1]} | "
                 f"{o['places'][0]}/{o['places'][1]} | {pt or '-'} | {a['edges']['shared']}/{a['edges']['coast']}/{a['edges']['land']} |")
    (out/'valhallasc-shape-table.md').write_text('\n'.join(L)+'\n')
    print('table written')


def load_world():
    m = json.loads((ROOT/'world/map.txt').read_text())
    return [dict(m, name='Greenmeadow')]+m['zones']


def is_water(rgb):
    r, g, b = rgb
    return b >= g-6 and b-r > 12


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=str(ROOT/'test-results/zone-shapes-preview'))
    ap.add_argument('--rule', default='median', choices=['median', 'total', 'nofloor'])
    ap.add_argument('--table', action='store_true', help='write the comparison table from the three summary files and exit')
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    if args.table:
        return write_table(out)

    atlas, _ = atlas_geography.generate()
    world = load_world()
    regions = {r['zone']: r for r in atlas['regions']}
    polys = {z: r['outline'][0] for z, r in regions.items()}
    pairs = {(l['a'], l['b']): l for l in atlas['links']}
    neighbours = defaultdict(set)
    for a, b in pairs:
        neighbours[a].add(b)
        neighbours[b].add(a)
    # per-edge ownership (same keys as atlas_geography.generate)
    owners = defaultdict(list)
    for z, p in polys.items():
        for a, b in zip(p, p[1:]+p[:1]):
            owners[tuple(sorted((tuple(a), tuple(b))))].append(z)
    shared = defaultdict(list)       # (a,b) -> edges
    own_edges = defaultdict(list)    # z -> (edge, kind, other)
    for edge, zs in owners.items():
        if len(zs) == 2:
            key = tuple(sorted(zs))
            shared[key].append(edge)
    img = Image.open(PNG).convert('RGB')
    ps = img.size[0]/atlas['width']   # painted PNG is 1758 wide, atlas frame is 2048
    for z, p in polys.items():
        for a, b in zip(p, p[1:]+p[:1]):
            edge = tuple(sorted((tuple(a), tuple(b))))
            zs = owners[edge]
            if len(zs) == 2:
                other = [o for o in zs if o != z][0]
                kind = 'shared' if tuple(sorted(zs)) in pairs else 'corner'
                own_edges[z].append((edge, kind, other))
                continue
            mx, my = (a[0]+b[0])/2, (a[1]+b[1])/2
            nx, ny = -(b[1]-a[1]), b[0]-a[0]
            ln = math.hypot(nx, ny) or 1
            nx, ny = nx/ln, ny/ln
            for sgn in (1, -1):
                q = (mx+sgn*nx*14, my+sgn*ny*14)
                if not inside(q, p):
                    break
            q = (max(0, min(atlas['width']-1, q[0])), max(0, min(atlas['height']-1, q[1])))
            px = img.getpixel((min(img.size[0]-1, int(q[0]*ps)), min(img.size[1]-1, int(q[1]*ps))))
            other_in = [o for o, pp in polys.items() if o != z and inside(q, pp)]
            kind = 'gap' if other_in else ('coast' if is_water(px) else 'land')
            own_edges[z].append((edge, kind, None))

    # ---- scale rule -------------------------------------------------------
    S = {z: world[z]['size'] for z in polys}
    A = {z: area(polys[z]) for z in polys}
    ratios = {z: S[z]**2/A[z] for z in polys}
    k2_median = statistics.median(ratios.values())
    k2_total = sum(v*v for v in S.values())/sum(A.values())
    k2 = {'median': k2_median, 'total': k2_total, 'nofloor': k2_median}[args.rule]
    scale = {}
    city_min = {}
    for z in polys:
        s = math.sqrt(k2)
        c = world[z].get('city')
        if c:
            cw, ch = c['x1']-c['x0'], c['y1']-c['y0']
            city_min[z] = city_min_scale(polys[z], s, cw, ch)
        if args.rule == 'nofloor':
            # deviation from strict proportion: never shrink (area >= old) and the city footprint must fit
            s = max(s, math.sqrt(ratios[z]), city_min.get(z, 0))
        scale[z] = s

    def tiles(z):
        xs = [q[0] for q in polys[z]]
        ys = [q[1] for q in polys[z]]
        s = scale[z]
        return (min(xs), min(ys), math.ceil((max(xs)-min(xs))*s), math.ceil((max(ys)-min(ys))*s), s)

    def to_tile(z, q):
        x0, y0, w, h, s = tiles(z)
        return ((q[0]-x0)*s, (q[1]-y0)*s)

    summary = []
    for z in sorted(polys):
        zd = world[z]
        x0, y0, W, H, s = tiles(z)
        poly_t = [to_tile(z, q) for q in polys[z]]
        PX = max(3, min(8, int(1500/max(W, H))))
        mask = Image.new('1', (W+2, H+2))
        ImageDraw.Draw(mask).polygon(poly_t, fill=1)
        mpx = mask.load()

        def in_new(x, y):
            return 0 <= int(x) < W+2 and 0 <= int(y) < H+2 and mpx[int(x), int(y)]
        sx, sy = W/S[z], H/S[z]

        def mp(x, y):
            return (x*sx, y*sy)
        counts = {}
        for key in ('slimes', 'npcs', 'places', 'crosses'):
            lst = zd.get(key, [])
            out_n = sum(1 for o in lst if not in_new(*mp(o['x'], o['y'])))
            counts[key] = (out_n, len(lst))
        pts_out = 0
        portal_rows = []
        kinds = defaultdict(int)
        for p in zd.get('portals', []):
            to = p['to']
            if to in neighbours[z]:
                chain = shared[tuple(sorted((z, to)))]
                chain_t = [(to_tile(z, a), to_tile(z, b)) for a, b in chain]
                d = chain_dist(mp(p['x'], p['y']), chain_t)
                portal_rows.append((p['id'], to, round(d, 1)))
                kinds['border'] += 1
            elif to in polys:
                kinds['far-atlas'] += 1
            else:
                kinds['inner'] += 1
        city = zd.get('city')
        city_fit = None
        if city:
            cw, ch = city['x1']-city['x0'], city['y1']-city['y0']
            cx, cy = mp((city['x0']+city['x1'])/2, (city['y0']+city['y1'])/2)
            corners = [(cx-cw/2, cy-ch/2), (cx+cw/2, cy-ch/2), (cx-cw/2, cy+ch/2), (cx+cw/2, cy+ch/2)]
            at_stretch = all(in_new(*c) for c in corners)
            possible = False
            for yy in range(0, H, 2):
                for xx in range(0, W, 2):
                    if all(in_new(xx+dx, yy+dy) for dx in (0, cw) for dy in (0, ch)) and \
                       all(in_new(xx+cw*fx, yy+ch*fy) for fx in (.25, .5, .75) for fy in (.25, .5, .75)):
                        possible = True
                        break
                if possible:
                    break
            city_fit = dict(min_scale_to_fit=round(city_min[z], 3), w=cw, h=ch, at_stretch=at_stretch, fits_anywhere=possible,
                            footprint_vs_area=round(cw*ch/(A[z]*s*s), 2))
        poly_tiles_area = A[z]*s*s
        row = dict(zone=z, name=zd['name'], old=S[z], new=[W, H], scale=round(s, 3),
                   old_area=S[z]**2, new_area=round(poly_tiles_area), ratio=round(poly_tiles_area/S[z]**2, 2),
                   outside=counts, portals=portal_rows, portal_kinds=dict(kinds), city=city_fit,
                   neighbours=sorted(neighbours[z]),
                   edges={k: sum(1 for e in own_edges[z] if e[1] == k) for k in ('shared', 'corner', 'coast', 'land', 'gap')})
        summary.append(row)

        # ---- picture ------------------------------------------------------
        x0a = min(q[0] for q in polys[z])
        y0a = min(q[1] for q in polys[z])
        crop = img.crop((int(x0a*ps), int(y0a*ps), int((x0a+W/s)*ps)+1, int((y0a+H/s)*ps)+1)).resize((W*PX, H*PX))
        dark = Image.eval(crop, lambda v: int(v*.35))
        big = Image.new('1', (W*PX, H*PX))
        ImageDraw.Draw(big).polygon([(a*PX, b*PX) for a, b in poly_t], fill=1)
        pic = Image.composite(crop, dark, big.convert('L'))
        pad = 150
        canvas = Image.new('RGB', (W*PX+2*pad, H*PX+2*pad+70), (24, 24, 28))  # title block above
        canvas.paste(pic, (pad, pad+70))
        d = ImageDraw.Draw(canvas)
        ox, oy = pad, pad+70

        def P(x, y):
            return (ox+x*PX, oy+y*PX)
        # tile grid every 20 tiles
        for g in range(0, max(W, H)+1, 20):
            if g <= W:
                d.line([P(g, 0), P(g, H)], fill=(255, 255, 255, 30) if False else (70, 70, 80), width=1)
                d.text((P(g, 0)[0]-8, oy-18), str(g), fill=(170, 170, 180), font=font(12))
            if g <= H:
                d.line([P(0, g), P(W, g)], fill=(70, 70, 80), width=1)
                d.text((ox-30, P(0, g)[1]-7), str(g), fill=(170, 170, 180), font=font(12))
        # redraw polygon region on top of the grid so the grid shows only outside
        canvas.paste(pic.crop((0, 0, W*PX, H*PX)), (ox, oy), big.convert('L'))
        # old square, stretched
        d.rectangle([P(0, 0), P(W, H)], outline=(120, 120, 130), width=1)
        colours = {n: NEIGHBOUR_COLOURS[i % len(NEIGHBOUR_COLOURS)] for i, n in enumerate(sorted(neighbours[z]))}
        legend = []
        for edge, kind, other in own_edges[z]:
            a, b = to_tile(z, edge[0]), to_tile(z, edge[1])
            col = {'coast': '#5ad7ff', 'land': '#ffb347', 'gap': '#ffffff', 'corner': '#888888'}.get(kind)
            if kind == 'shared':
                col = colours[other]
            d.line([P(*a), P(*b)], fill=col, width=5 if kind == 'shared' else 4)
        # raw vertices
        for q in poly_t:
            d.ellipse([P(*q)[0]-3, P(*q)[1]-3, P(*q)[0]+3, P(*q)[1]+3], fill=(255, 255, 255))
        # old content
        for o in zd.get('slimes', []):
            x, y = P(*mp(o['x'], o['y']))
            ok = in_new(*mp(o['x'], o['y']))
            if ok:
                d.ellipse([x-2, y-2, x+2, y+2], fill=(235, 90, 90))
            else:
                d.line([x-4, y-4, x+4, y+4], fill=(255, 40, 40), width=2)
                d.line([x-4, y+4, x+4, y-4], fill=(255, 40, 40), width=2)
        for key, col in (('npcs', (90, 160, 255)), ('places', (255, 230, 90)), ('crosses', (200, 120, 255))):
            for o in zd.get(key, []):
                x, y = P(*mp(o['x'], o['y']))
                ok = in_new(*mp(o['x'], o['y']))
                d.rectangle([x-3, y-3, x+3, y+3], fill=col if ok else None, outline=(255, 40, 40) if not ok else col, width=2)
        if city:
            cw, ch = city['x1']-city['x0'], city['y1']-city['y0']
            cx, cy = mp((city['x0']+city['x1'])/2, (city['y0']+city['y1'])/2)
            col = (80, 230, 120) if city_fit['at_stretch'] else ((255, 190, 60) if city_fit['fits_anywhere'] else (255, 70, 70))
            # drawn on a clipped layer: a 126x126 city is bigger than its own outline
            layer = Image.new('RGBA', canvas.size, (0, 0, 0, 0))
            ld = ImageDraw.Draw(layer)
            ld.rectangle([P(cx-cw/2, cy-ch/2), P(cx+cw/2, cy+ch/2)], outline=col+(255,), width=3)
            ld.text((P(cx-cw/2, cy-ch/2)[0]+4, P(cx-cw/2, cy-ch/2)[1]+4), f"{city['name']} {cw}x{ch} (true size)",
                    fill=col+(255,), font=font(13, True))
            box = (10, 110, canvas.size[0]-10, oy+H*PX+2)
            canvas.paste(layer.crop(box), (box[0], box[1]), layer.crop(box))
            d = ImageDraw.Draw(canvas)
        for pr in zd.get('portals', []):
            x, y = P(*mp(pr['x'], pr['y']))
            to = pr['to']
            col = colours.get(to, (255, 255, 255)) if to in neighbours[z] else (190, 190, 190)
            d.polygon([(x, y-7), (x+6, y+5), (x-6, y+5)], fill=col, outline=(0, 0, 0))
            if to in neighbours[z]:
                chain = shared[tuple(sorted((z, to)))]
                best = None
                for a, b in chain:
                    a, b = to_tile(z, a), to_tile(z, b)
                    for t in [i/20 for i in range(21)]:
                        q = (a[0]+(b[0]-a[0])*t, a[1]+(b[1]-a[1])*t)
                        dd = math.hypot(q[0]-mp(pr['x'], pr['y'])[0], q[1]-mp(pr['x'], pr['y'])[1])
                        if best is None or dd < best[0]:
                            best = (dd, q)
                d.line([(x, y), P(*best[1])], fill=col, width=2)
        # title and legend
        d.text((20, 12), f"Zone {z}: {zd['name']}", fill=(255, 255, 255), font=font(26, True))
        d.text((20, 46), f"old {S[z]}x{S[z]} = {S[z]**2} tiles   ->   proposed bbox {W}x{H}, outline area {round(poly_tiles_area)} tiles "
                         f"({row['ratio']}x)   scale {s:.3f} tiles/atlas px   rule: {args.rule}", fill=(220, 220, 230), font=font(15))
        d.text((20, 68), "Old content stretched onto the new bbox (an upper bound: SHAPE-DATA re-lays it). Red X/box = outside outline. "
                         "City box at TRUE size: green fits at stretched spot, amber fits only elsewhere, red cannot fit.",
               fill=(170, 170, 185), font=font(12))
        lx = ox+W*PX+14
        ly = oy
        for n, col in colours.items():
            d.rectangle([lx, ly, lx+14, ly+14], fill=col)
            d.text((lx+20, ly-1), f"{world[n]['name'][:14]}", fill=(230, 230, 230), font=font(12))
            ly += 20
        for label, col in (('coast (water)', '#5ad7ff'), ('outer land', '#ffb347'), ('gap/other', '#ffffff')):
            d.rectangle([lx, ly, lx+14, ly+14], fill=col)
            d.text((lx+20, ly-1), label, fill=(230, 230, 230), font=font(12))
            ly += 20
        lines = []
        for key, (o, n) in counts.items():
            lines.append(f"{key}: {o}/{n} outside")
        for pid, to, dd in portal_rows:
            lines.append(f"{pid}->{to}: {dd} t off border")
        for i, t in enumerate(lines[:24]):
            d.text((20 if False else ox, oy+H*PX+8+i*0), '', font=font(1))
        ty = oy+H*PX+8
        d.text((ox, ty), "   ".join(f"{k}: {o}/{n} outside" for k, (o, n) in counts.items()), fill=(240, 200, 200), font=font(14))
        if portal_rows:
            d.text((ox, ty+22), "portal to its shared border (tiles): " + ", ".join(f"{pid}={dd}" for pid, to, dd in portal_rows[:7]),
                   fill=(200, 230, 200), font=font(13))
        safe = ''.join(c for c in zd['name'].lower().replace(' ', '-') if c.isalnum() or c == '-')
        canvas.save(out/f"valhallasc-shape-z{z:02d}-{safe}-{args.rule}.png")

    # ---- overview ---------------------------------------------------------
    cell = 330
    cols = 6
    rows = math.ceil(len(summary)/cols)
    ov = Image.new('RGB', (cols*cell, rows*cell+90), (24, 24, 28))
    d = ImageDraw.Draw(ov)
    d.text((16, 10), f"Old square (grey) vs proposed outline (colour), same tile scale. Rule: {args.rule} "
                     f"(k = {math.sqrt(k2):.3f} tiles/atlas px)", fill=(255, 255, 255), font=font(20, True))
    d.text((16, 42), "Number under each zone: old side -> new bbox, area ratio. Red = footprint problem.", fill=(200, 200, 210), font=font(14))
    pxs = 1.0
    for i, r in enumerate(summary):
        z = r['zone']
        cx0, cy0 = (i % cols)*cell+10, (i//cols)*cell+90
        maxd = max(r['old'], *r['new'], 1)
        pxs = (cell-60)/420.0 if False else (cell-70)/max(r['old'], r['new'][0], r['new'][1])
        # use one global scale instead: 0.62 px/tile
        pxs = 0.62
        d.rectangle([cx0, cy0+20, cx0+r['old']*pxs, cy0+20+r['old']*pxs], outline=(130, 130, 140), width=2)
        x0, y0, W, H, s = tiles(z)
        poly = [(cx0+(q[0]-x0)*s*pxs, cy0+20+(q[1]-y0)*s*pxs) for q in polys[z]]
        problem = bool(r['city'] and not r['city']['fits_anywhere']) or r['ratio'] < .5
        col = (255, 90, 90) if problem else (110, 200, 140)
        d.polygon(poly, outline=col, fill=(col[0]//4, col[1]//4, col[2]//4))
        d.text((cx0, cy0-2), f"{z} {r['name'][:20]}", fill=(255, 255, 255), font=font(13, True))
        d.text((cx0, cy0+20+max(r['old'], H)*pxs+4), f"{r['old']} -> {W}x{H}  ({r['ratio']}x)", fill=col, font=font(13))
    ov.save(out/f"valhallasc-shape-overview-{args.rule}.png")

