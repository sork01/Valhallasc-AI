#!/usr/bin/env python3
"""Derive which weather each map may have (docs/weather.md, WEATHER-RULES).

The theme of every map in world/map.txt is looked up in THEMES below. A map with `copies` (a private dungeon) or an
enclosed theme never has weather. A theme missing from the table is an error, so a new zone cannot silently get no
rule. `wind` carries a variant that decides what the wind blows.

    python3 scripts/weather_zones.py          # print the table
    python3 scripts/weather_zones.py --write  # rewrite docs/weather-zones.txt
    python3 scripts/weather_zones.py --check  # exit 1 when the file is stale or a theme is unmapped
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "weather-zones.txt"
DATA = ROOT / "world" / "weather.txt"

# Themes whose maps are enclosed even though they are public (docs/day-night.md).
ENCLOSED = {"orrery", "deep", "heartwood", "arena"}

# theme -> (types in the order they are listed, wind variant or None). "clear" is always allowed and is listed first.
THEMES = {
    "meadow": (["rain", "fog", "thunderstorm", "wind"], "leaves"),
    "ember": (["fog", "wind"], "ash"),
    "frost": (["snow", "fog"], None),
    "fen": (["rain", "fog", "thunderstorm"], None),
    "city": (["snow", "fog"], None),  # Skaldholm, beyond the glacier
    "wyrd": (["rain", "fog", "thunderstorm", "wind"], "leaves"),
    "sky": (["fog", "wind", "thunderstorm"], "cloud"),
    "nacre": ([], None),  # beneath a quiet tide: clear only
    "astral": (["fog", "wind"], "stardust"),
    "prismwaste": (["wind", "sandstorm"], "shards"),
    "moonspore": (["rain", "fog"], None),
    "asterion": (["wind"], "cloud"),
    "stormglass": (["rain", "thunderstorm", "wind"], "dust"),
    "sunward": (["rain", "fog", "wind"], "leaves"),
    "ribbonwild": (["rain", "wind"], "petals"),
    "tanglecrown": (["rain", "fog", "thunderstorm"], None),
    "worldtree": (["rain", "fog", "wind"], "leaves"),
    "lapiserg": (["wind", "sandstorm"], "dust"),
    "frostwake": (["snow", "fog", "wind"], "snow"),
    "cairnspine": (["rain", "snow", "fog", "wind"], "dust"),
    # The four seasons: the type follows the quadrant the hero stands in (see docs/weather.md).
    "yearwheel": (["rain", "thunderstorm", "wind", "snow", "fog"], "leaves"),
}


def derive():
    world = json.loads((ROOT / "world" / "map.txt").read_text())
    maps = [(0, "meadow", world.get("name", "Greenmeadow"), None, world.get("interior", False))] + [
        (i + 1, z.get("theme", ""), z.get("name", "?"), z.get("copies"), z.get("interior", False)) for i, z in enumerate(world["zones"])
    ]
    rows, missing = [], []
    for number, theme, name, copies, interior in maps:
        if copies or interior or theme in ENCLOSED or theme.startswith("cathedral") or theme in _DUNGEON_THEMES(world):
            rows.append((number, name, theme, None))
        elif theme in THEMES:
            rows.append((number, name, theme, THEMES[theme]))
        else:
            missing.append((number, name, theme))
    return rows, missing


def _DUNGEON_THEMES(world):
    return {z.get("theme") for z in world["zones"] if z.get("copies")}


def render():
    rows, missing = derive()
    if missing:
        raise SystemExit("Themes with no weather rule: " + ", ".join(f"{n} {name} ({t!r})" for n, name, t in missing))
    lines = ["# Generated by scripts/weather_zones.py from world/map.txt. Do not edit by hand."]
    outside = [r for r in rows if r[3] is not None]
    inside = [r for r in rows if r[3] is None]
    lines.append(f"outdoor {len(outside)}")
    for n, name, theme, (types, variant) in outside:
        allowed = ["clear"] + types
        extra = f" (wind blows {variant})" if "wind" in types and variant else ""
        lines.append(f"  zone {n:>2} {name} [{theme}]: {', '.join(allowed)}{extra}")
    lines.append(f"enclosed {len(inside)} (never any weather)")
    lines += [f"  zone {n:>2} {name} [{theme}]" for n, name, theme, _ in inside]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = render()
    rows, _ = derive()
    data = json.dumps([dict(zone=n, theme=theme, allowed=(["clear"] + rule[0]) if rule else ["clear"],
                            variant=rule[1] if rule else None, inside=rule is None)
                       for n, _name, theme, rule in rows], indent=2) + "\n"
    if "--write" in sys.argv:
        OUT.write_text(text)
        DATA.write_text(data)
    elif "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text or not DATA.exists() or DATA.read_text() != data:
            sys.exit("weather zone outputs are stale: run python3 scripts/weather_zones.py --write")
    else:
        print(text, end="")
