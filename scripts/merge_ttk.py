#!/usr/bin/env python3
"""Merge the five private class outputs from ttk.sh into a readable comparison table."""
import argparse
import json
from pathlib import Path

CLASSES = ('warrior', 'mage', 'assassin', 'priest', 'hunter')


def merge(paths):
    rows = []
    for path in paths:
        data = json.loads(Path(path).read_text())
        if not data:
            raise ValueError(f'{path} has no cases')
        classes = {row['class'] for row in data}
        if len(classes) != 1:
            raise ValueError(f'{path} must contain exactly one class: {classes}')
        rows.extend(data)
    if {row['class'] for row in rows} != set(CLASSES):
        raise ValueError('expected reports for warrior, mage, assassin, priest and hunter')
    by_case = {}
    for row in rows:
        variant = (row['spread'], row['rotation'], row['foe'], row['consumables'])
        key = (*variant, row['level'], row['class'])
        if key in by_case:
            raise ValueError(f'duplicate case {key}')
        by_case[key] = row
    variants = sorted({key[:4] for key in by_case})
    lines = ['# Kill-time report', '', 'Generated by `bash scripts/ttk-parallel.sh` from five isolated in-memory class runs.',
             'Each cell is **median kill seconds / damage per landed monster hit**. `FAIL` means at least one seed did not kill the target; failed seeds count at the rotation cap.', '']
    for variant in variants:
        spread, rotation, foe, consumables = variant
        levels = sorted({key[4] for key in by_case if key[:4] == variant})
        counts = {by_case[key]['runs'] for key in by_case if key[:4] == variant}
        if len(counts) != 1:
            raise ValueError(f'inconsistent run count for {variant}: {counts}')
        runs = counts.pop()
        lines += [f'## {spread}, {rotation}, {foe}, consumables={int(consumables)}', '',
                  f'{runs} seeded run(s) per case.' + (' **Provisional: the TTK-RUN target is nine seeds.**' if runs < 9 else ''), '',
                  '| Level | Enemy | ' + ' | '.join(c.title() for c in CLASSES) + ' |',
                  '| ---: | --- | ' + ' | '.join('---:' for _ in CLASSES) + ' |']
        for level in levels:
            matching = [by_case.get((*variant, level, c)) for c in CLASSES]
            if any(row is None for row in matching):
                raise ValueError(f'missing class at level {level} for {variant}')
            enemy = matching[0]['enemy']
            cells = [f"{row['seconds']['median']:g} s / {row['damagePerHit']:g}" + (' FAIL' if row['failures'] else '') for row in matching]
            lines.append(f'| {level} | {enemy} | ' + ' | '.join(cells) + ' |')
        lines.append('')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', required=True)
    parser.add_argument('reports', nargs=5)
    args = parser.parse_args()
    Path(args.out).write_text(merge(args.reports))


if __name__ == '__main__':
    main()
