#!/usr/bin/env python3
"""Merge the five class outputs of dps-parallel.sh into docs/dps-report.md (DPS-REPORT)."""
import argparse
import json
import statistics
from pathlib import Path

CLASSES = ('warrior', 'mage', 'assassin', 'priest', 'hunter')
# Outlier lines of the DPS-REPORT task.
CLASS_SPREAD = 1.3
DOMINANT_SHARE = 40.
NEGLIGIBLE_SHARE = 2.


def load(paths):
    rows = {}
    for path in paths:
        data = json.loads(Path(path).read_text())
        if not data:
            raise ValueError(f'{path} has no cases')
        for row in data:
            key = (row['class'], row['level'])
            if key in rows:
                raise ValueError(f'duplicate case {key}')
            rows[key] = row
    if {key[0] for key in rows} != set(CLASSES):
        raise ValueError('expected reports for warrior, mage, assassin, priest and hunter')
    levels = sorted({key[1] for key in rows})
    for class_ in CLASSES:
        for level in levels:
            if (class_, level) not in rows:
                raise ValueError(f'missing {class_} level {level}')
    return rows, levels


def fmt(n):
    return f'{n:,.0f}'


def pct(n):
    return '-' if n == 0 else f'{n:.1f}'


def report(rows, levels):
    first = rows[(CLASSES[0], levels[0])]
    lines = [
        '# Damage per second by class (training dummy)',
        '',
        'Generated by `bash scripts/dps-parallel.sh` (`DPS-RUN`) from five isolated in-memory class runs; this report is the input to later balancing and changes no game stat.',
        '',
        '## Method',
        '',
        f'- Target: a training dummy. An ordinary monster of the level made harmless **in the harness only** (no damage, a health pool that cannot run out, rooted so it never moves). The game has no enemy defence, resistance or evasion, so it has none either. Source: `server/src/world/dps_tests.rs`.',
        '- Character: the level\'s normal green progression gear (no refinement, no set bonus, no consumables), the even default attribute allocation, every skill and rank earned by the level.',
        '- Rotation: the mercenaries\' own code (`World::auto_play` / `ai_combat`): every damaging skill when ready and in reach, buffs when none is active, heals only when someone is hurt. Resource costs and cooldowns apply. Dashes are never used by that code, so a damaging dash shows 0 casts (see the list of uncast skills).',
        f'- Duration: {first["seconds"]:.0f} s of game time counted from the first point of damage; the character starts inside melee reach, so the walk is not measured.',
        f'- Seeds: {first["runs"]} per class and level (crits, hit rolls and damage spread are random). DPS is the median over the seeds; the damage shares are computed from the mean damage of each source, so they add up to 100.',
        '- Damage is read from the server\'s own accounting by source: a skill id, the basic attack (`Basic attack`, including bolts it fires) or a set bonus. Heals are not damage; against a dummy nobody is hurt, so healing skills correctly show 0 casts.',
        '',
        '## Damage per second at each level',
        '',
        'Median damage per second. `x median` is the class\'s DPS divided by the median of the five classes at that level; `best/worst` is the best class\'s DPS over the worst\'s.',
        '',
        '| Level | ' + ' | '.join(c.capitalize() for c in CLASSES) + ' | Median | Best / worst |',
        '| ---: | ' + ' | '.join('---:' for _ in CLASSES) + ' | ---: | ---: |',
    ]
    outliers = []
    for level in levels:
        dps = {c: rows[(c, level)]['dpsMedian'] for c in CLASSES}
        med = statistics.median(dps.values())
        best, worst = max(dps.values()), min(dps.values())
        ratio = best / worst if worst else float('inf')
        cells = [f'{fmt(dps[c])} ({dps[c] / med:.2f}x)' for c in CLASSES]
        lines.append(f'| {level} | ' + ' | '.join(cells) + f' | {fmt(med)} | {ratio:.2f} |')
        for c in CLASSES:
            if med and (dps[c] / med > CLASS_SPREAD or dps[c] / med < 1 / CLASS_SPREAD):
                word = 'above' if dps[c] > med else 'below'
                outliers.append(f'- Level {level}: **{c}** is {dps[c] / med:.2f}x the median class ({fmt(dps[c])} against {fmt(med)}), {word} the {CLASS_SPREAD}x line.')
    lines += ['', 'Total damage over the minute (mean of the seeds), with the run-to-run range of DPS:', '',
              '| Level | ' + ' | '.join(c.capitalize() for c in CLASSES) + ' |',
              '| ---: | ' + ' | '.join('---:' for _ in CLASSES) + ' |']
    for level in levels:
        cells = []
        for c in CLASSES:
            r = rows[(c, level)]
            cells.append(f'{fmt(r["totalMean"])} ({fmt(r["dpsMin"])}-{fmt(r["dpsMax"])} dps)')
        lines.append(f'| {level} | ' + ' | '.join(cells) + ' |')

    lines += ['', '## Where each class\'s damage comes from', '',
              'Rows are the skills the class has by level 99 (the unlock level in brackets), columns the levels. Each cell is the share of that class\'s damage in per cent; `-` means no damage (not unlocked yet, never cast, or not a damaging skill).', '']
    uncast = []
    for c in CLASSES:
        ids = {}
        for level in levels:
            for s in rows[(c, level)]['sources']:
                ids.setdefault(s['id'], (s['name'], s['unlock']))
        order = sorted(ids, key=lambda i: (i not in ('basic',), ids[i][1], i))
        lines += [f'### {c.capitalize()}', '',
                  '| Source | ' + ' | '.join(str(l) for l in levels) + ' |',
                  '| --- | ' + ' | '.join('---:' for _ in levels) + ' |']
        for i in order:
            name, unlock = ids[i]
            label = name if i in ('basic', 'set_bonus') else f'{name} ({unlock})'
            cells = []
            for level in levels:
                found = [s for s in rows[(c, level)]['sources'] if s['id'] == i]
                share = found[0]['share'] if found else 0
                cells.append(pct(share))
                if found:
                    if share > DOMINANT_SHARE:
                        outliers.append(f'- {c.capitalize()} level {level}: **{name}** is {share:.1f}% of the class\'s damage (above {DOMINANT_SHARE:.0f}%).')
                    elif 0 < share < NEGLIGIBLE_SHARE and i not in ('basic', 'set_bonus'):
                        outliers.append(f'- {c.capitalize()} level {level}: **{name}** is only {share:.1f}% of the class\'s damage (below {NEGLIGIBLE_SHARE:.0f}%).')
            lines.append(f'| {label} | ' + ' | '.join(cells) + ' |')
        lines.append('')
        for level in levels:
            for i in rows[(c, level)]['uncast']:
                found = [s for s in rows[(c, level)]['sources'] if s['id'] == i][0]
                uncast.append((c, found['name'], found['unlock'], level))

    lines += ['## Casts and hits per minute', '',
              'Mean casts (c) and damaging hits (h) of each source in the minute, at levels 50 and 99. A skill that lands many hits per cast is multi-hit or area damage.', '']
    for level in [l for l in (50, levels[-1]) if l in levels]:
        lines += [f'### Level {level}', '', '| Class | Source | Casts | Hits | Damage | Share % |', '| --- | --- | ---: | ---: | ---: | ---: |']
        for c in CLASSES:
            for s in rows[(c, level)]['sources']:
                if s['damage'] > 0 or s['casts'] > 0:
                    lines.append(f'| {c} | {s["name"]} | {s["casts"]:g} | {s["hits"]:g} | {fmt(s["damage"])} | {pct(s["share"])} |')
        lines.append('')

    lines += ['## Outliers', '']
    lines += outliers or ['- None.']
    lines += ['', '## Skills that were never cast', '',
              'A skill with 0 casts is one the mercenaries\' code never fires or never affords. It is listed, not hidden.', '',
              '- **Never fired by that code**: dashes (Charge, Blink, Roll Away, Lunge) and heals, because nobody is hurt in this test (Second Wind, Mend, Prayer of Healing, Guardian Light, Divine Hymn). These are expected.',
              '- **Energy starvation** (assassin and hunter): energy returns at 10 per second and the code casts the first affordable skill in the class\'s list order, so the cheap early skills spend all of it and the costlier later ones (35-50 energy) never reach their cost. Those skills\' damage is missing from the class totals above, so the assassin and hunter numbers describe this rotation, not what a player who saves energy for the strong skills would do. Judge the balance of those two classes with that in mind (a second, priority-with-reserve rotation is a follow-up).', '']
    if uncast:
        by_skill = {}
        for c, name, unlock, level in uncast:
            by_skill.setdefault((c, name, unlock), []).append(level)
        for (c, name, unlock), lvls in sorted(by_skill.items()):
            lines.append(f'- {c.capitalize()}: **{name}** (unlocks at {unlock}), uncast at levels {", ".join(map(str, lvls))}.')
    else:
        lines.append('- None.')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', required=True)
    parser.add_argument('reports', nargs='+')
    args = parser.parse_args()
    rows, levels = load(args.reports)
    Path(args.out).write_text(report(rows, levels))


if __name__ == '__main__':
    main()
