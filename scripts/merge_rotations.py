#!/usr/bin/env python3
"""Merge the five class outputs of best-rotation-parallel.sh into docs/best-rotations.md (DPS-ROTATION)."""
import argparse
import json
from pathlib import Path

CLASSES = ('warrior', 'mage', 'assassin', 'priest', 'hunter')
SLOT_WORD = {'cast': '', 'hold': ' (hold)', 'off': ''}


def load(paths):
    rows = {}
    for path in paths:
        for row in json.loads(Path(path).read_text()):
            key = (row['class'], row['level'])
            if key in rows:
                raise ValueError(f'duplicate case {key}')
            rows[key] = row
    if {key[0] for key in rows} != set(CLASSES):
        raise ValueError('expected reports for warrior, mage, assassin, priest and hunter')
    levels = sorted({key[1] for key in rows})
    for class_ in CLASSES:
        for level in levels:
            if (class_, level) not in rows:
                raise ValueError(f'missing {class_} level {level}')
    return rows, levels


def fmt(n):
    return f'{n:,.0f}'


def rotation_text(row):
    live = [s for s in row['rotation'] if s['slot'] != 'off']
    off = [s['name'] for s in row['rotation'] if s['slot'] == 'off']
    text = ' > '.join(f'{s["name"]}{SLOT_WORD[s["slot"]]}' for s in live) or 'basic attack only'
    if off:
        text += f'; never cast: {", ".join(off)}'
    return text


def report(rows, levels):
    first = rows[(CLASSES[0], levels[0])]
    lines = [
        '# Best rotation per class (training dummy)',
        '',
        'Generated by `bash scripts/best-rotation-parallel.sh` (`DPS-ROTATION`). This is the rotation that dealt the most damage in a minute against the harmless dummy of `docs/dps-report.md`; it is a measurement for balancing and changes no game stat or mercenary behaviour.',
        '',
        '## Method',
        '',
        '- Same test as `docs/dps-report.md`: the level\'s normal green gear, even attribute spread, no consumables, a rooted dummy with no defence, 60 s counted from the first hit.',
        '- A rotation is a **priority list**. Every tick the list is walked from the top and the first skill that is off cooldown, in reach and affordable is cast. A skill marked **hold** that is ready and in reach but not affordable stops the walk, so energy, rage or mana builds up for it instead of being spent on the skills below. A skill that is **never cast** is left out because casting it costs more than it earns. The basic attack runs underneath and is not part of the list.',
        '- Skills that can add damage take part: damaging skills (dashes that hurt included) and damage, haste and crit buffs, cast when no buff of that kind is running. Heals, shields, dodge and regeneration do nothing against a dummy and are left out.',
        '- Search (`server/src/world/rotation_tests.rs`): steepest-ascent hill climbing over each skill\'s state (never, cast, hold) and over adjacent swaps in the order, from three starting lists, on 2 seeds of 40 s each (a neighbour must gain 0.3% to be taken). The finalists and the mercenaries\' own rotation are then measured again on **9 other seeds**; the table shows the median of those, so a lucky roll in the search does not count. A hill climb finds a good rotation, not a proven optimum.',
        '- The mercenary column is `World::auto_play`, as in `docs/dps-report.md`.',
        '',
        '## Damage per second: best rotation against the mercenaries\' rotation',
        '',
        '| Level | ' + ' | '.join(f'{c.capitalize()} best (mercenary)' for c in CLASSES) + ' |',
        '| ---: | ' + ' | '.join('---:' for _ in CLASSES) + ' |',
    ]
    for level in levels:
        cells = []
        for c in CLASSES:
            r = rows[(c, level)]
            cells.append(f'{fmt(r["bestDps"])} ({fmt(r["brainDps"])}) **{r["uplift"]:+.1f}%**')
        lines.append(f'| {level} | ' + ' | '.join(cells) + ' |')
    lines += ['', 'Best DPS per level, side by side (the ratio to the median class is what balancing compares):', '',
              '| Level | ' + ' | '.join(c.capitalize() for c in CLASSES) + ' | Best / worst |',
              '| ---: | ' + ' | '.join('---:' for _ in CLASSES) + ' | ---: |']
    for level in levels:
        dps = [rows[(c, level)]['bestDps'] for c in CLASSES]
        lines.append(f'| {level} | ' + ' | '.join(fmt(d) for d in dps) + f' | {max(dps) / min(dps):.2f} |')

    lines += ['', '## The rotations', '',
              'Read left to right: the first skill that can be cast is cast. `(hold)` means wait for the resource instead of casting something below it.', '']
    for c in CLASSES:
        lines += [f'### {c.capitalize()}', '', '| Level | Best DPS | Rotation |', '| ---: | ---: | --- |']
        for level in levels:
            r = rows[(c, level)]
            lines.append(f'| {level} | {fmt(r["bestDps"])} | {rotation_text(r)} |')
        lines.append('')
        lines += ['Where the damage comes from at levels 50 and 99 with the best rotation (share of the class\'s damage, per cent; casts per minute in brackets):', '']
        for level in [l for l in (50, levels[-1]) if l in levels]:
            parts = [f'{s["name"]} {s["share"]:.1f}% ({s["casts"]:g})' if s['id'] not in ('basic', 'set_bonus') else f'{s["name"]} {s["share"]:.1f}%'
                     for s in rows[(c, level)]['sources'] if s['share'] > 0 or s['casts'] > 0]
            lines.append(f'- Level {level}: ' + ', '.join(parts))
        lines.append('')

    lines += ['## Search notes', '',
              '| Class | Level | Search evaluations | Finalists (median DPS on the validation seeds) |', '| --- | ---: | ---: | --- |']
    for c in CLASSES:
        for level in levels:
            r = rows[(c, level)]
            finalists = '; '.join(f'{f["start"]}: {fmt(f["dps"])}' for f in r['finalists'])
            lines.append(f'| {c} | {level} | {r["evals"]} | {finalists} |')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', required=True)
    parser.add_argument('reports', nargs='+')
    args = parser.parse_args()
    rows, levels = load(args.reports)
    Path(args.out).write_text(report(rows, levels))


if __name__ == '__main__':
    main()
